#' Summarize Fitted Models for Batch-Effect Diagnostics
#'
#' Extracts model coefficients and constructs residual representations used
#' for diagnosing additive and multiplicative batch effects. The appropriate
#' method is selected automatically according to the class of `diag_model`.
#'
#' @param diag_model A fitted diagnostic-model object returned by
#'   [diag_model_gen()].
#'
#' @param ... Additional arguments passed to the corresponding S3 method.
#'
#' @return An object of class `"diag_summary"` containing:
#' \describe{
#'   \item{coef}{
#'     Estimated model coefficients for each feature.
#'   }
#'   \item{resid_add}{
#'     A matrix of observations after removal of the modeled non-batch
#'     mean structure. Batch-related mean variation is retained, making this
#'     representation suitable for assessing additive batch effects.
#'   }
#'   \item{resid_mul}{
#'     A matrix of ordinary model residuals after removal of the full fitted
#'     mean structure, including modeled batch effects. This representation
#'     can be used to assess residual scale or variance-related batch effects.
#'   }
#' }
#'
#' @details
#' `diag_model_summary()` is an S3 generic. Methods are provided for
#' linear models, generalized additive models, and linear mixed-effects
#' models generated by [diag_model_gen()].
#'
#' For linear and generalized additive models, `resid_add` is obtained by
#' reconstructing the fitted contribution of all model terms except terms
#' whose names begin with `"batch"`, and subtracting this contribution from
#' the observed data.
#'
#' For linear mixed-effects models, `resid_add` removes the selected
#' non-batch fixed effects together with the specified random-intercept
#' contributions. The ordinary model residuals are stored in `resid_mul`.
#'
#' @seealso
#' [diag_model_gen()]
#'
#' @export
diag_model_summary <- function(diag_model, ...) {
  UseMethod("diag_model_summary")
}

#' @rdname diag_model_summary
#'
#' @method diag_model_summary lm_model
#'
#' @export
diag_model_summary.lm_model <- function(diag_model, ...){
  fits <- diag_model$fits
  Y <- as.matrix(diag_model$data)
  coefs <- lapply(fits, coef)
  fix_list <- lapply(fits, function(model) {
    X <- stats::model.matrix(model)
    beta <- stats::coef(model)
    X <- X[, !grepl("^batch", colnames(X)), drop = FALSE]
    beta <- beta[!grepl("^batch", names(beta))]
    common <- intersect(colnames(X), names(beta))
    if (length(common) == 0) {
      return(numeric(nrow(Y)))
    }
    missing <- setdiff(colnames(X), names(beta))
    if (length(missing) > 0) {
      stop("Missing coefficient(s) for: ", paste(missing, collapse = ", "))
    }
    as.numeric(X[, common, drop = FALSE] %*% beta[common])
  })
  fix_effects <- do.call(cbind, fix_list)
  if (nrow(Y) != nrow(fix_effects)) {
    stop("Row mismatch: nrow(data) != nobs in lm fits.")
  }
  resid_add <- Y - fix_effects
  resid_mul <- sapply(fits, resid, simplify = "matrix")
  diag_summary <- list(coef = coefs, resid_add = resid_add, resid_mul = resid_mul)
  class(diag_summary) <- "diag_summary"
  return(diag_summary)
}


#' @rdname diag_model_summary
#'
#' @method diag_model_summary gam_model
#'
#' @export
diag_model_summary.gam_model <- function(diag_model, ...){
  fits <- diag_model$fits
  Y <- diag_model$data
  coefs <- lapply(fits, coef)
  fix_list <- lapply(fits, function(model) {
    X <- stats::model.matrix(model)
    beta <- stats::coef(model)
    keep_X <- !grepl("^batch", colnames(X))
    X <- X[, keep_X, drop = FALSE]
    keep_b <- !grepl("^batch", names(beta))
    beta <- beta[keep_b]
    common <- intersect(colnames(X), names(beta))
    if (length(common) == 0) {
      stop("No overlapping terms between model.matrix and coefficients after filtering.")
    }
    if (length(common) != ncol(X)) {
      missing <- setdiff(colnames(X), names(beta))
      if (length(missing) > 0) {
        stop("Missing coefficient(s) for: ", paste(missing, collapse = ", "))
      }
      X <- X[, common, drop = FALSE]
    }
    as.numeric(X %*% beta[common])
  })
  fix_effects <- do.call(cbind, fix_list)
  Y_mat <- as.matrix(Y)
  if (nrow(Y_mat) != nrow(fix_effects)) {
    stop("Row mismatch: nrow(data) != nobs in GAM fits.")
  }
  resid_add <- Y_mat - fix_effects
  resid_mul <- sapply(fits, resid, simplify = "matrix")
  diag_summary <- list(coef = coefs, resid_add = resid_add, resid_mul = resid_mul)
  class(diag_summary) <- "diag_summary"
  return(diag_summary)
}

#' @rdname diag_model_summary
#'
#' @param random Character vector specifying the grouping factors whose
#'   random-intercept contributions should be removed when constructing
#'   `resid_add`. Each name must correspond to a grouping factor present
#'   in the fitted mixed-effects models.
#'
#' @method diag_model_summary lmerMod_model
#'
#' @export
diag_model_summary.lmerMod_model <- function(diag_model, random, ...){
  fits <- diag_model$fits
  Y    <- diag_model$data
  df   <- diag_model$mod
  coefs <- sapply(fits, function(m) lme4::fixef(m), simplify = "matrix")
  if (!is.character(random) || length(random) == 0) {
    stop("`random` must be a non-empty character vector of grouping-factor names.")
  }
  rand_mat <- sapply(fits, function(m) {
    N <- nrow(df)
    add_total <- numeric(N)
    re_all <- lme4::ranef(m)
    for (r in random) {
      if (!r %in% names(re_all)) {
        stop("Grouping factor `", r, "` not found in ranef(model). Available: ",
             paste(names(re_all), collapse = ", "))
      }
      re_mat <- re_all[[r]]
      if (!"(Intercept)" %in% colnames(re_mat)) {
        stop("Random intercept not found for grouping factor: ", r)
      }
      ids <- as.character(df[[r]])
      idx <- match(ids, rownames(re_mat))
      add <- numeric(N)
      ok <- !is.na(idx)
      add[ok] <- re_mat[idx[ok], "(Intercept)"]
      add_total <- add_total + add
    }
    add_total
  })
  rand_mat <- as.matrix(rand_mat)
  X <- lme4::getME(fits[[1]], "X")
  keep <- !grepl("^batch", colnames(X))
  X <- X[, keep, drop = FALSE]
  X <- X[, colnames(X) != "(Intercept)", drop = FALSE]
  common <- intersect(colnames(X), rownames(coefs))
  if (length(common) != ncol(X)) {
    missing <- setdiff(colnames(X), rownames(coefs))
    stop("Coefficient(s) missing for X columns: ", paste(missing, collapse = ", "))
  }
  B <- coefs[common, , drop = FALSE]
  B <- apply(B, 2, as.numeric)
  resid_add <- Y - (X[, common, drop = FALSE] %*% B + rand_mat)
  resid_mul <- sapply(fits, resid, simplify = "matrix")
  diag_summary <- list(coef = coefs, resid_add = resid_add, resid_mul = resid_mul)
  class(diag_summary) <- "diag_summary"
  return(diag_summary)
}


#' Fit Feature-Wise Models for Batch Diagnostics
#'
#' Fits a separate regression model to each feature and constructs an
#' object suitable for use with [diag_model_summary()].
#'
#' @param bat A vector specifying the batch membership of each observation.
#'
#' @param data A numeric matrix or data frame with observations in rows and
#'   features in columns.
#'
#' @param covar Optional data frame containing covariates to include in the
#'   feature-wise models.
#'
#' @param model A model-fitting function, such as [stats::lm()],
#'   [mgcv::gam()], or [lme4::lmer()].
#'
#' @param formula A model formula specifying the covariate structure.
#'   Its exact form depends on the supplied `model`.
#'
#' @param ref.batch Optional reference batch used when constructing the batch
#'   design matrix. Defaults to `NULL`.
#'
#' @param bat_adjust Logical indicating whether batch terms should be included
#'   in the fitted models. Defaults to `TRUE`.
#'
#' @param ... Additional arguments passed to the model-fitting function.
#'
#' @return A fitted model object with an S3 class determined by the underlying
#'   model type. The resulting object can be passed to
#'   [diag_model_summary()].
#'
#'
#' @seealso
#' [diag_model_summary()]
diag_model_gen <- function(bat, data, covar, model, formula = NULL, ref.batch = NULL, bat_adjust = TRUE, ...){
  if (bat_adjust){
    batch_result <- batch_matrix(bat, ref.batch = ref.batch)
    fitted_model <- model_fitting(data, batch_result$batch_matrix, covar, model, formula, ...)
    class_type <- class(fitted_model$fits[[1]])
  }else{
    fits <- apply(data, 2, function(y) {
      if(is.null(covar)){
        dat <- data.frame(y = y)}else{
          dat <- data.frame(y = y, covar)
        }
      do.call(model, list(formula = formula, data = dat, ...))
    })
    fitted_model <- list(data = data, fits = unname(as.list(fits)))
    names(fitted_model$fits) <- colnames(data)
    class_type <- class(fits[[1]])
  }
  class(fitted_model) <- paste0(class_type[1], "_model")
  return(fitted_model)
}


#' Test for Batch Effects Across Features
#'
#' Compares full and reduced feature-wise models to test whether the `batch`
#' term significantly contributes to model fit. P-values are adjusted across
#' features using the Bonferroni method.
#'
#' @param diag_model A fitted diagnostic-model object containing one fitted
#'   model per feature. Supported models are `lm`, `gam`, and `lmerMod`.
#'
#' @param batch Batch variable used in the fitted models.
#'
#' @return A list containing:
#' \describe{
#'   \item{test_table}{
#'     A data frame with feature names, raw p-values, and Bonferroni-adjusted
#'     p-values.
#'   }
#'   \item{perc.sig}{
#'     Percentage of features with adjusted p-values below 0.05.
#'   }
#' }
#'
#' @details
#' For each feature, the full model is compared with a reduced model excluding
#' the `batch` term. F-tests are used for `lm` and `gam` models, and a
#' likelihood-ratio test is used for `lmerMod` models. Non-finite p-values are
#' replaced by 1.
#'
#' @export
anova_test <- function(diag_model, batch) {
  fits <- diag_model$fits
  p_raw <- sapply(fits, function(fit) {
    full_model <- fit
    reduced_model <- update(full_model, . ~ . - batch)

    if (inherits(full_model, "gam")) {
      anova_tab <- mgcv::anova.gam(reduced_model, full_model, test = "F")
      pval <- anova_tab[["Pr(>F)"]][2]
    } else if (inherits(full_model, "lm")) {
      anova_tab <- stats::anova(reduced_model, full_model, test = "F")
      pval <- anova_tab[["Pr(>F)"]][2]
    } else if (inherits(full_model, "lmerMod")) {
      anova_tab <- stats::anova(reduced_model, full_model, refit = TRUE)
      pval <- anova_tab[["Pr(>Chisq)"]][2]
    } else {
      stop("`anova_test()` currently supports only `lm`, `gam`, and `lmerMod` models.")
    }

    if (length(pval) != 1L || !is.finite(pval)) {pval <- 1}
    as.numeric(pval)
  })

  p_adj <- stats::p.adjust(p_raw, method = "bonferroni")

  percent_below_0.05 <- mean(p_adj < 0.05, na.rm = TRUE) * 100

  num_sig <- paste0(sprintf("%.2f", percent_below_0.05), "%")

  test_result <- data.frame(feature = names(fits), p_value_raw = as.numeric(p_raw), p_value = as.numeric(p_adj), row.names = NULL)

  return(list(test_table = test_result, perc.sig = num_sig))
}

#' Kenward-Roger Test for Batch Effects
#'
#' Tests the contribution of the `batch` term in feature-wise linear
#' mixed-effects models using the Kenward-Roger approximation. P-values are
#' adjusted across features using the Bonferroni method.
#'
#' @param diag_model A fitted diagnostic-model object containing one
#'   mixed-effects model per feature.
#'
#' @param batch Batch variable used in the fitted models.
#'
#' @param ... Additional arguments.
#'
#' @return A list containing:
#' \describe{
#'   \item{test_table}{
#'     A data frame with feature names and Bonferroni-adjusted p-values.
#'   }
#'   \item{perc.sig}{
#'     Percentage of features with adjusted p-values below 0.05.
#'   }
#' }
#'
#' @details
#' For each feature, the full model is compared with a reduced model excluding
#' the `batch` term using a Kenward-Roger test.
#'
#' @export
kenward_test <- function(diag_model, batch, ...){
  fits <- diag_model$fits
  p_value <- sapply(fits, function(fit){
    lmm1 <- fit
    lmm2 <- update(fit, . ~ . - batch)
    kr.test <- KRmodcomp(lmm1, lmm2) %>% tidy() %>% pull(.data[["p.value"]])
    return(kr.test)
  }) |> p.adjust(method = "bonferroni") |> round(3)
  test_result <- data.frame(cbind(feature = names(fits), p_value))
  percent_below_0.05 <- mean(p_value < 0.05) * 100
  num_sig <- paste0(sprintf("%.2f", percent_below_0.05), "%")
  return(list(test_table = test_result, perc.sig = num_sig))
}

#' Kruskal-Wallis Test for Additive Batch Effects
#'
#' Tests for differences in feature-wise additive residual distributions
#' across batches using the Kruskal-Wallis test. P-values are adjusted using
#' the Bonferroni method.
#'
#' @param resid_add A numeric matrix of additive residuals, with observations
#'   in rows and features in columns.
#'
#' @param batch A vector specifying batch membership for each observation.
#'
#' @return A list containing a table of Bonferroni-adjusted p-values and the
#'   percentage of features with adjusted p-values below 0.05.
#'
#' @export
kruskal_test <- function(resid_add, batch){
  G <- ncol(resid_add)
  p_value <- sapply(1:G, function(g) kruskal.test(resid_add[,g] ~ batch) %>% tidy() %>% pull(.data[["p.value"]])) |> p.adjust(method = "bonferroni") |> round(3)
  test_result <- data.frame(cbind(feature = colnames(resid_add), p_value))
  percent_below_0.05 <- mean(p_value < 0.05) * 100
  num_sig <- paste0(sprintf("%.2f", percent_below_0.05), "%")
  return(list(test_table = test_result, perc.sig = num_sig))
}

