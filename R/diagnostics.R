#' Prepare PCA Scores for Batch Diagnostics
#'
#' Fits feature-wise models, extracts additive residuals, and performs PCA on
#' the residual matrix for visualization of batch-related structure.
#'
#' @param bat A vector specifying batch or site membership.
#' @param data A numeric matrix or data frame with observations in rows and
#'   features in columns.
#' @param covar Optional data frame of covariates included in the fitted models.
#' @param model Model-fitting function used for feature-wise regression.
#' @param formula Optional model formula.
#' @param ref.batch Optional reference batch.
#' @param bat_adjust Logical indicating whether batch effects are included in
#'   model fitting.
#' @param test_param A list of additional arguments passed to
#'   [diag_model_summary()], such as random-effect grouping factors.
#' @param ... Additional arguments passed to the model-fitting procedure.
#'
#' @return A list containing the PCA score matrix `F_t` and the batch vector
#'   `bat`.
#'
#' @export
pca_prep <- function(bat, data, covar, model, formula = NULL, ref.batch = NULL, bat_adjust = TRUE, test_param = list(random = NULL), ...){
  if(is.data.frame(data) || is.matrix(data)){
    diag_model_result <- diag_model_gen(
      bat, data, covar, model, formula, ref.batch, bat_adjust, ...
    )
    diag_summary <- do.call(diag_model_summary, c(list(diag_model = diag_model_result), test_param))
    resid_add_df <- diag_summary$resid_add
    F_t <- prcomp(resid_add_df, center = TRUE, scale. = TRUE)$x
    return(list(F_t = F_t, bat = bat))
  }else{
    stop("`data` must be a data.frame, matrix, or a list of those.")
  }
}


#' Plot PCA Scores by Batch
#'
#' Creates a scatter plot of two selected principal components, colored by
#' batch or site.
#'
#' @param pca_prep_result An object returned by [pca_prep()].
#' @param type Character specifying the plot type. Currently retained for
#'   compatibility but not used.
#' @param pc_1 Integer specifying the principal component for the x-axis.
#'   Defaults to `1`.
#' @param pc_2 Integer specifying the principal component for the y-axis.
#'   Defaults to `2`.
#' @param ellipse Logical indicating whether to display batch-specific
#'   68-percent concentration ellipses. Defaults to `TRUE`.
#'
#' @return A `ggplot` object.
#'
#' @export
pca_plot <- function(pca_prep_result, type = "within", pc_1 = 1, pc_2 = 2, ellipse = TRUE){
  pc_pair <- paste0("PC", c(pc_1, pc_2))
  element_names <- names(pca_prep_result)
  F_df <- pca_prep_result$F_t %>% data.frame() %>% mutate(bat = pca_prep_result$bat)
  plt <- ggplot(
    F_df,
    aes(x = .data[[pc_pair[1]]], y = .data[[pc_pair[2]]], color = .data[["bat"]])
  ) +
    geom_point(alpha = 0.7, size = 1.6, stroke = 0) +
    coord_equal() +
    labs(
      x = pc_pair[1],
      y = pc_pair[2],
      color = "Batch / Site"
    ) +
    scale_color_brewer(palette = "Set2") +
    theme_minimal(base_size = 12) +
    theme(
      panel.grid.minor = element_blank(),
      panel.grid.major = element_line(linewidth = 0.2),
      strip.text = element_text(face = "bold"),
      strip.background = element_rect(fill = "grey95", color = NA),
      legend.position = "bottom",
      legend.title = element_text(face = "bold"),
      plot.title.position = "plot",
      panel.spacing = unit(6, "pt"),
      axis.title = element_text(face = "bold")
    )
  if(ellipse){
    plt + stat_ellipse(level = 0.68, linewidth = 0.6, show.legend = FALSE)
  }else{
    plt
  }

}

#' Prepare t-SNE Embedding for Batch Diagnostics
#'
#' Fits feature-wise models, extracts additive residuals, and computes a
#' two-dimensional t-SNE embedding for visualization of batch-related
#' structure.
#'
#' @param bat A vector specifying batch or site membership.
#' @param data A numeric matrix or data frame with observations in rows and
#'   features in columns.
#' @param covar Optional data frame of covariates included in the fitted models.
#' @param model Model-fitting function used for feature-wise regression.
#' @param formula Optional model formula.
#' @param ref.batch Optional reference batch.
#' @param bat_adjust Logical indicating whether batch effects are included in
#'   model fitting.
#' @param test_param A list of additional arguments passed to
#'   [diag_model_summary()].
#' @param ... Additional arguments passed to the model-fitting procedure.
#'
#' @return A data frame containing the two t-SNE dimensions and batch
#'   membership.
#'
#' @export
tsne_prep <- function(bat, data, covar, model, formula = NULL, ref.batch = NULL, bat_adjust = TRUE, test_param = list(random = NULL), ...){
  if(is.data.frame(data) || is.matrix(data)){
    diag_model_result <- diag_model_gen(
      bat, data, covar, model, formula, ref.batch, bat_adjust, ...
    )
    diag_summary <- do.call(diag_model_summary, c(list(diag_model = diag_model_result), test_param))
    resid_add_df <- diag_summary$resid_add
    ts <- Rtsne::Rtsne(resid_add_df)
    df <- data.frame(
      dim1 = ts$Y[,1],
      dim2 = ts$Y[,2],
      batch = bat
    )
    return(df)
  }else{
    stop("`data` must be a data.frame, matrix, or a list of those.")
  }
}

