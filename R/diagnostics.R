#' Compute R-Squared for a Single Association
#'
#' Fits a linear model between two variables and returns the coefficient of
#' determination.
#'
#' @param y Numeric outcome vector.
#' @param x Predictor variable.
#'
#' @return A numeric \eqn{R^2} value, or `NA` when the association cannot be
#'   estimated.
#'
#' @export
get_r2 <- function(y, x) {
  keep <- stats::complete.cases(y, x)
  y <- y[keep]
  x <- x[keep]

  if (length(y) < 3L) {return(NA_real_)}
  if (length(unique(x)) <= 1L) {return(NA_real_)}

  dat <- data.frame(y = y, x = x)
  fit <- stats::lm(y ~ x, data = dat)
  unname(summary(fit)$r.squared)
}

#' Summarize Principal-Component Associations
#'
#' Performs PCA on the input data and computes the association between each
#' selected principal component and each metadata variable using \eqn{R^2}.
#'
#' @param data Numeric matrix with observations in rows and features in
#'   columns.
#' @param metadata Data frame containing metadata variables.
#' @param n_pc Number of principal components to evaluate. Defaults to `5`.
#' @param scale_data Logical indicating whether variables should be scaled
#'   before PCA. Defaults to `TRUE`.
#' @param variable_groups Optional named vector assigning metadata variables
#'   to display groups.
#'
#' @return A data frame containing metadata variables, principal components,
#'   and \eqn{R^2} values. PCA variance proportions and the fitted PCA object
#'   are stored as attributes.
#'
#' @export
pc_assoc_table <- function(
    data,
    metadata,
    n_pc = 5,
    scale_data = TRUE,
    variable_groups = NULL
) {

  data <- as.matrix(data)
  metadata <- as.data.frame(metadata)

  if (nrow(data) != nrow(metadata)) {
    stop("`data` and `metadata` must have the same number of rows.", call. = FALSE)
  }

  pca <- stats::prcomp(data, center = TRUE, scale. = scale_data)
  n_pc <- min(n_pc, ncol(pca$x))
  scores <- pca$x[, seq_len(n_pc), drop = FALSE]

  out <- list()
  idx <- 1L
  for (j in seq_len(ncol(metadata))) {
    var_name <- colnames(metadata)[j]
    x <- metadata[[j]]
    if (is.character(x)) {x <- as.factor(x)}
    for (k in seq_len(n_pc)) {
      r2 <- get_r2(y = scores[, k], x = x)
      out[[idx]] <- data.frame(
        Variable = var_name,
        PC = paste0("PC", k),
        R2 = r2,
        stringsAsFactors = FALSE
      )
      idx <- idx + 1L
    }
  }

  result <- do.call(rbind, out)

  if (!is.null(variable_groups)) {
    if (is.null(names(variable_groups))) {
      stop("`variable_groups` must be a named vector.", call. = FALSE)
    }
    result$Panel <- variable_groups[result$Variable]
  } else {
    result$Panel <- "Metadata"
  }

  pc_var <- pca$sdev^2 / sum(pca$sdev^2)

  attr(result, "pc_variance") <- pc_var[seq_len(n_pc)]
  attr(result, "pca") <- pca
  result
}

