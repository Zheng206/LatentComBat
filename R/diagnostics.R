#' Canonical Correlation Diagnostic
#'
#' Performs canonical correlation analysis between surrogate variables and a
#' block of explanatory variables after removing constant and linearly
#' dependent columns.
#'
#' @param H Numeric matrix of surrogate variables.
#' @param X_block Data frame or matrix containing a block of explanatory
#'   variables.
#' @param tol Numeric tolerance used to identify near-constant and
#'   linearly dependent columns. Defaults to `1e-8`.
#'
#' @return A list containing canonical correlations, canonical scores,
#'   loadings, retained variables, matrix ranks, and complete-case indicators.
#'
#' @export
cca_diagnostic <- function(H, X_block, tol = 1e-8) {
  H <- as.matrix(H)
  X_block <- as.data.frame(X_block)
  X <- make_model_matrix_block(
    X_block
  )
  keep_rows <- stats::complete.cases(H, X)

  H <- H[keep_rows,,drop = FALSE]
  X <- X[keep_rows,,drop = FALSE]
  keep_H <- apply(H, 2, stats::sd) > tol
  keep_X <- apply(X, 2, stats::sd) > tol
  H <- H[,keep_H,drop = FALSE]
  X <- X[,keep_X,drop = FALSE]

  if (ncol(H) == 0L) {
    stop("No non-constant columns remain in `H`.")
  }

  if (ncol(X) == 0L) {
    stop("No non-constant columns remain in `X_block`.")
  }

  Hs <- scale(H); Xs <- scale(X)

  qr_H <- qr(Hs, tol = tol)
  rank_H <- qr_H$rank
  keep_H_idx <- qr_H$pivot[seq_len(rank_H)]
  Hs_red <- Hs[, keep_H_idx,drop = FALSE]

  qr_X <- qr(Xs, tol = tol)
  rank_X <- qr_X$rank
  keep_X_idx <- qr_X$pivot[seq_len(rank_X)]
  Xs_red <- Xs[, keep_X_idx,drop = FALSE]

  cc <- stats::cancor(Hs_red,Xs_red)

  U <- Hs_red %*% cc$xcoef
  V <- Xs_red %*% cc$ycoef

  colnames(U) <- paste0("U", seq_len(ncol(U)))
  colnames(V) <- paste0("V", seq_len(ncol(V)))

  sv_loadings <- stats::cor(Hs_red, U)
  technical_loadings <- stats::cor(Xs_red,V)

  list(
    cancor = cc,
    cor = cc$cor,
    U = U,
    V = V,
    sv_loadings = sv_loadings,
    block_loadings = technical_loadings,
    H_used = Hs_red,
    X_used = Xs_red,
    H_columns = colnames(Hs_red),
    X_columns = colnames(Xs_red),
    rank_H = rank_H,
    rank_X = rank_X,
    keep_rows = keep_rows
  )
}

