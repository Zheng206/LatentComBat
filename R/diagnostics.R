#' Construct a Model Matrix for a Variable Block
#'
#' Converts a data frame of variables into a numeric design matrix, removing
#' constant variables and the intercept.
#'
#' @param df A data frame or object coercible to a data frame.
#'
#' @return A numeric model matrix with non-constant encoded variables.
#'
#' @export
make_model_matrix_block <- function(df) {
  df <- as.data.frame(df)
  keep <- vapply(df, function(x) length(unique(x[!is.na(x)])) > 1L, logical(1))
  df <- df[, keep, drop = FALSE]
  if (ncol(df) == 0L) {return(matrix(numeric(0), nrow = nrow(df), ncol = 0L))}
  X <- stats::model.matrix(~ ., data = df)
  if ("(Intercept)" %in% colnames(X)) {X <- X[, colnames(X) != "(Intercept)", drop = FALSE]}
  X
}

#' Compute Association with a Single Variable
#'
#' Fits a linear model relating a surrogate variable to one metadata variable
#' and returns the corresponding coefficient of determination.
#'
#' @param y Numeric outcome vector.
#' @param x Predictor variable.
#' @param var_name Character name of the predictor.
#' @param panel_name Character label identifying the variable group.
#'
#' @return A one-row data frame containing the variable name, panel, and
#'   model \eqn{R^2}.
#'
#' @export
assoc_one <- function(y, x, var_name, panel_name) {
  dat <- data.frame(y = y, x = x)
  fit <- stats::lm(y ~ x, data = dat)
  s <- summary(fit)
  data.frame(
    SV = NA_character_,
    Variable = var_name,
    Panel = panel_name,
    R2 = unname(s$r.squared),
    stringsAsFactors = FALSE
  )
}


#' Summarize Surrogate-Variable Associations
#'
#' Computes associations between surrogate variables and batch or biological
#' covariates using feature-wise \eqn{R^2} values.
#'
#' @param H Numeric matrix of surrogate variables, with observations in rows.
#' @param batch_df Optional data frame of batch or technical variables.
#' @param cov_df Optional data frame of biological or other covariates.
#'
#' @return A data frame containing surrogate-variable names, metadata
#'   variables, variable groups, and \eqn{R^2} values.
#'
#' @export
sv_assoc_table <- function(H, batch_df = NULL, cov_df = NULL) {
  H <- as.matrix(H)
  sv_names <- colnames(H)
  if (is.null(sv_names)) {sv_names <- paste0("SV", seq_len(ncol(H)))}

  out <- list()

  if (!is.null(batch_df)) {
    batch_df <- as.data.frame(batch_df)
    for (k in seq_len(ncol(H))) {
      for (j in seq_len(ncol(batch_df))) {
        tmp <- assoc_one(H[, k], batch_df[[j]], colnames(batch_df)[j], "Batch variables")
        tmp$SV <- sv_names[k]
        out[[length(out) + 1L]] <- tmp
      }
    }
  }

  if (!is.null(cov_df)) {
    cov_df <- as.data.frame(cov_df)
    for (k in seq_len(ncol(H))) {
      for (j in seq_len(ncol(cov_df))) {
        tmp <- assoc_one(H[, k], cov_df[[j]], colnames(cov_df)[j], "Covariates")
        tmp$SV <- sv_names[k]
        out[[length(out) + 1L]] <- tmp
      }
    }
  }

  dplyr::bind_rows(out)
}

